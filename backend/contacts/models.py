import uuid
from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models, transaction
from common.identifiers import next_identifier
from .normalization import normalize_identifier


class Source(models.TextChoices):
    MANUAL = 'manual', 'Manual'
    WEBSITE = 'website', 'Website'
    WHATSAPP = 'whatsapp', 'WhatsApp'
    CALL = 'call', 'Call'


class Contact(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    contact_id = models.CharField(max_length=30, unique=True, editable=False)
    full_name = models.CharField(max_length=200)
    branch = models.ForeignKey('branches.Branch', on_delete=models.PROTECT, related_name='contacts')
    source = models.CharField(max_length=12, choices=Source.choices, default=Source.MANUAL)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, null=True, related_name='created_contacts')
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at', '-id']
        indexes = [models.Index(fields=['branch', 'full_name'])]

    @transaction.atomic
    def save(self, *args, **kwargs):
        if self._state.adding:
            if self.contact_id:
                raise ValidationError('Contact IDs are generated by the database-backed allocator.')
            self.contact_id = next_identifier('contact', 'LMT-C')
        elif Contact.objects.filter(pk=self.pk).exclude(contact_id=self.contact_id).exists():
            raise ValidationError('Contact ID cannot be changed.')
        super().save(*args, **kwargs)

    def __str__(self):
        return '%s — %s' % (self.contact_id, self.full_name)


class ContactIdentifier(models.Model):
    class Kind(models.TextChoices):
        PHONE = 'phone', 'Phone'
        EMAIL = 'email', 'Email'
        EXTERNAL = 'external', 'External provider ID'

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    contact = models.ForeignKey(Contact, on_delete=models.PROTECT, related_name='identifiers')
    kind = models.CharField(max_length=12, choices=Kind.choices)
    value = models.CharField(max_length=254)
    normalized_value = models.CharField(max_length=254, editable=False)
    namespace = models.CharField(max_length=40, blank=True, default='')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['created_at', 'id']
        indexes = [models.Index(fields=['kind', 'namespace', 'normalized_value'])]
        constraints = [
            models.UniqueConstraint(fields=['contact', 'kind', 'namespace', 'normalized_value'], name='unique_contact_identifier'),
            # Phones/emails can be shared. Provider resource IDs cannot.
            models.UniqueConstraint(fields=['namespace', 'normalized_value'], condition=models.Q(kind='external'), name='unique_external_identity'),
            models.CheckConstraint(condition=(models.Q(kind__in=['phone', 'email'], namespace='') |
                (models.Q(kind='external') & ~models.Q(namespace=''))), name='valid_identity_namespace'),
        ]

    def save(self, *args, **kwargs):
        if not self._state.adding:
            raise ValidationError('Identifiers are immutable; add another identifier instead.')
        self.normalized_value, self.namespace = normalize_identifier(self.kind, self.value, self.namespace)
        super().save(*args, **kwargs)


class DuplicateReview(models.Model):
    class Status(models.TextChoices):
        PENDING = 'pending', 'Pending'
        SEPARATE = 'separate', 'Confirmed distinct person'
        LINKED = 'linked', 'Linked to existing person'
        REJECTED = 'rejected', 'Rejected intake'

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    branch = models.ForeignKey('branches.Branch', on_delete=models.PROTECT, related_name='duplicate_reviews')
    full_name = models.CharField(max_length=200)
    source = models.CharField(max_length=12, choices=Source.choices)
    identifiers = models.JSONField(default=list)
    candidates = models.ManyToManyField(Contact, related_name='duplicate_reviews')
    # Non-null for an identifier-addition review, otherwise a new-contact intake.
    target_contact = models.ForeignKey(Contact, null=True, on_delete=models.PROTECT, related_name='identifier_reviews')
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.PENDING, db_index=True)
    resolved_contact = models.ForeignKey(Contact, null=True, on_delete=models.PROTECT, related_name='resolved_reviews')
    reason = models.TextField(blank=True)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name='submitted_reviews')
    resolved_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.PROTECT, related_name='resolved_duplicate_reviews')
    created_at = models.DateTimeField(auto_now_add=True)
    resolved_at = models.DateTimeField(null=True)

    class Meta:
        ordering = ['-created_at', '-id']
