import uuid
from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models, transaction
from common.identifiers import next_identifier, enquiry_branch_code
from django.utils import timezone
from contacts.models import Source


class Lead(models.Model):
    class Status(models.TextChoices):
        NEW = 'new', 'New'
        CONTACTED = 'contacted', 'Contacted'
        QUALIFIED = 'qualified', 'Qualified'
        WON = 'won', 'Won'
        LOST = 'lost', 'Lost'

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    lead_id = models.CharField(max_length=30, unique=True, editable=False)
    contact = models.ForeignKey('contacts.Contact', on_delete=models.PROTECT, related_name='leads')
    branch = models.ForeignKey('branches.Branch', on_delete=models.PROTECT, related_name='leads')
    origin_branch = models.ForeignKey('branches.Branch', null=True, on_delete=models.PROTECT, related_name='originated_leads', editable=False)
    origin_branch_code = models.CharField(max_length=8, blank=True, editable=False)
    origin_branch_verified = models.BooleanField(default=True, editable=False)
    legacy_lead_id = models.CharField(max_length=30, blank=True, default='', editable=False, db_index=True)
    owner = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT, related_name='leads')
    title = models.CharField(max_length=200)
    source = models.CharField(max_length=12, choices=Source.choices, default=Source.MANUAL)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.NEW)
    next_action = models.CharField(max_length=500, blank=True)
    next_action_at = models.DateTimeField(null=True, blank=True)
    no_followup_reason = models.CharField(max_length=500, blank=True)
    unassigned_reason = models.CharField(max_length=500, blank=True)
    assignment_version = models.PositiveBigIntegerField(default=0, editable=False)
    acknowledgement_due_at = models.DateTimeField(null=True, editable=False)
    acknowledged_at = models.DateTimeField(null=True, editable=False)
    routing_attempts = models.PositiveIntegerField(default=0, editable=False)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.PROTECT, related_name='created_leads')
    created_at = models.DateTimeField(auto_now_add=True)
    received_at = models.DateTimeField(default=timezone.now, editable=False)
    received_via = models.CharField(max_length=20, default='crm_recorded', editable=False,
        choices=[('crm_recorded', 'CRM creation date'), ('website_received', 'Website receipt'), ('call_started', 'Call start time'), ('whatsapp_received', 'WhatsApp message time')])
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at', '-id']
        indexes = [models.Index(fields=['branch', 'status', 'next_action_at']),
                   models.Index(fields=['owner', 'status']), models.Index(fields=['contact', 'status'])]
        constraints = [
            models.CheckConstraint(condition=models.Q(status__in=['new', 'contacted', 'qualified', 'won', 'lost']), name='valid_lead_status'),
            models.CheckConstraint(condition=(models.Q(owner__isnull=False) | ~models.Q(unassigned_reason='')), name='unowned_lead_requires_reason'),
            models.CheckConstraint(condition=(models.Q(status__in=['won', 'lost']) | ~models.Q(no_followup_reason='') |
                (~models.Q(next_action='') & models.Q(next_action_at__isnull=False))), name='active_lead_requires_next_action'),
        ]

    @transaction.atomic
    def save(self, *args, **kwargs):
        if self._state.adding:
            if self.lead_id:
                raise ValidationError('Lead IDs are generated by the database-backed allocator.')
            self.origin_branch = self.branch
            self.origin_branch_code = enquiry_branch_code(self.branch)
            self.origin_branch_verified = True
            self.lead_id = next_identifier('lead', f'LMT-{self.origin_branch_code}-L')
        else:
            original = Lead.objects.filter(pk=self.pk).values('lead_id', 'origin_branch_id', 'origin_branch_code', 'origin_branch_verified', 'legacy_lead_id').first()
            if original and any(getattr(self, key) != value for key, value in original.items()):
                raise ValidationError('Enquiry ID and first branch details cannot be changed.')
        super().save(*args, **kwargs)

    def __str__(self):
        return self.lead_id
